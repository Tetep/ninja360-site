#!/usr/bin/env python3
"""Build components/entity-score.html from data/entity-confidence.json.

The number on the page is counted here from the item statuses. It is never typed by hand.
Run from the repo root:   python3 seo/build-entity-score.py
Then paste components/entity-score.html into the GHL page (see README workflow).
"""
import datetime
import html
import json
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
SRC = ROOT / "data" / "entity-confidence.json"
OUT = ROOT / "components" / "entity-score.html"
CHIP = {"done": "Done", "progress": "In progress", "not_started": "Not started"}


def main():
    data = json.loads(SRC.read_text(encoding="utf-8"))
    allowed = set(data["statuses"])
    belts, total_done, total_items = [], 0, 0
    for belt in data["belts"]:
        for item in belt["items"]:
            if item["status"] not in allowed:
                sys.exit("bad status %r on %s" % (item["status"], item["id"]))
        done = sum(1 for i in belt["items"] if i["status"] == "done")
        belts.append((belt, done, len(belt["items"])))
        total_done += done
        total_items += len(belt["items"])

    as_of = datetime.date.fromisoformat(data["as_of"])
    pretty = as_of.strftime("%B %-d, %Y")
    e = html.escape

    tiles = "".join(
        '<div class="ec-belt ec-{k}"><b>{n}</b><span>{d} of {t}</span><small>{ti}</small></div>'.format(
            k=e(b["key"]), n=e(b["name"]), d=d, t=t, ti=e(b["title"]))
        for b, d, t in belts)

    lists = ""
    for b, d, t in belts:
        rows = "".join(
            '<li class="ec-i ec-{s}"><span class="ec-s">{c}</span><span>{l}</span></li>'.format(
                s=i["status"], c=CHIP[i["status"]], l=e(i["label"]))
            for i in b["items"])
        lists += '<div class="ec-col"><h3>{n}</h3><ul>{r}</ul></div>'.format(n=e(b["name"]), r=rows)

    out = """<!-- ENTITY CONFIDENCE SELF-CHECK. Generated by seo/build-entity-score.py from data/entity-confidence.json.
     Do not edit by hand: change the JSON, re-run the script, re-paste. Needs the page's n-* base styles (every page has them). -->
<style>
.ec-tiles{display:grid;grid-template-columns:repeat(3,minmax(0,1fr));gap:14px;margin:22px 0 8px}
.ec-belt{background:#fff;border:1px solid var(--n-line);border-radius:10px;padding:14px 16px}
.ec-belt b{display:block;font-size:12px;letter-spacing:.14em;text-transform:uppercase;color:var(--n-muted);font-weight:800}
.ec-belt span{display:block;font-size:28px;font-weight:800;color:var(--n-ink);margin-top:4px;font-variant-numeric:tabular-nums}
.ec-belt small{color:var(--n-muted);font-size:13px}
.ec-cols{display:grid;grid-template-columns:repeat(3,minmax(0,1fr));gap:22px;margin-top:22px}
.ec-col h3{font-size:15px;font-weight:800;margin:0 0 8px}
.ec-col ul{list-style:none;margin:0;padding:0}
.ec-i{display:flex;gap:10px;align-items:baseline;padding:8px 0;border-top:1px solid var(--n-line);font-size:14px;color:var(--n-ink)}
.ec-s{flex:0 0 86px;font-size:11px;font-weight:800;letter-spacing:.06em;text-transform:uppercase;color:var(--n-muted)}
.ec-done .ec-s{color:#1f7a45}
.ec-progress .ec-s{color:var(--n-red-dk)}
.ec-top{margin-top:22px;font-size:15px;color:var(--n-ink);max-width:760px}
.ec-asof{margin-top:10px;font-size:13px;color:var(--n-muted)}
@media(max-width:780px){.ec-tiles,.ec-cols{grid-template-columns:minmax(0,1fr)}}
</style>
<section class="n-section" id="entity-confidence" style="background:var(--n-soft)"><div class="n-wrap">
  <p class="n-eyebrow">Entity Confidence</p>
  <h2 class="n-h2">@DONE@ of @TOTAL@ checks complete</h2>
  <p class="n-sub">We score ourselves on the same AI-Search NAP standard we use on client audits. This is where Ninja 360 Digital Media stands as of @PRETTY@.</p>
  <div class="ec-tiles">@TILES@</div>
  <div class="ec-cols">@LISTS@</div>
  <p class="ec-top"><b>Top conflict:</b> @TOP@</p>
  <p class="ec-asof">@STANDARD@. Counted from the @TOTAL@ checks above; as of @PRETTY@.</p>
</div></section>
"""
    for token, value in (("@DONE@", str(total_done)), ("@TOTAL@", str(total_items)), ("@PRETTY@", pretty),
                         ("@TILES@", tiles), ("@LISTS@", lists),
                         ("@TOP@", e(data["top_conflict"]["public"])), ("@STANDARD@", e(data["standard"]))):
        out = out.replace(token, value)
    OUT.write_text(out, encoding="utf-8")
    print("wrote %s" % OUT.relative_to(ROOT))
    for b, d, t in belts:
        print("  %-11s %d of %d" % (b["name"], d, t))
    print("  TOTAL       %d of %d  (%.0f%%)" % (total_done, total_items, 100.0 * total_done / total_items))


if __name__ == "__main__":
    main()
